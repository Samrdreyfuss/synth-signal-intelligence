-- ============================================================================
-- 06_derived_signals.sql
-- Theme, quarterly and FDE signals computed from FACT_CRM_EVENTS, replacing the
-- hand-written saved tables in the dashboard. Same column shapes as the saved
-- tables so code can switch between them. Saved tables are left untouched.
-- Windows: prior = 2025-04-01..2026-03-31 (12 months), current = 2026-04-01..2026-10-17.
-- ============================================================================
CREATE SCHEMA IF NOT EXISTS SYNTH_SIGNAL_DB.DERIVED;

-- Eligible CRM theme mentions: one row per (event, theme), excluded account names removed.
CREATE OR REPLACE VIEW SYNTH_SIGNAL_DB.DERIVED.THEME_MENTIONS
  COMMENT = 'CRM events matched to themes by phrase, excluded accounts removed'
AS
SELECT e.EVENT_ID, d.THEME, e.ACCOUNT_ID, c.ACCOUNT_NAME, TO_DATE(e.PERFORMED_DATE) AS EVENT_DATE,
       CONTAINS(LOWER(e.DESCRIPTION), 'via portfolio company') AS VIA_PORTCO
FROM SYNTH_SIGNAL_DB.ANALYTICS.FACT_CRM_EVENTS e
JOIN SYNTH_SIGNAL_DB.ANALYTICS.DIM_THEME_DEFINITIONS d ON CONTAINS(LOWER(e.DESCRIPTION), d.PHRASE)
JOIN SYNTH_SIGNAL_DB.ANALYTICS.DIM_SALESFORCE__COMPANIES c ON c.ACCOUNT_ID = e.ACCOUNT_ID
WHERE TO_DATE(e.PERFORMED_DATE) >= '2024-07-01'
  AND NOT REGEXP_LIKE(LOWER(c.ACCOUNT_NAME), '.*(stealth|insight partners|new co|newco).*')
  AND c.ACCOUNT_NAME NOT LIKE '%(%' AND c.ACCOUNT_NAME NOT LIKE '% / %';

CREATE OR REPLACE VIEW SYNTH_SIGNAL_DB.DERIVED.ENTERPRISE_THEMES
  COMMENT = 'Same shape as SIGNAL_SAVED_FILES.ENTERPRISE_THEMES, computed from CRM'
AS
WITH w AS (
  SELECT THEME,
         COUNT_IF(EVENT_DATE BETWEEN '2025-04-01' AND '2026-03-31') AS PRIOR_MENTIONS,
         COUNT_IF(EVENT_DATE BETWEEN '2026-04-01' AND '2026-10-17') AS CURRENT_MENTIONS,
         COUNT(DISTINCT IFF(EVENT_DATE BETWEEN '2026-04-01' AND '2026-10-17', ACCOUNT_ID, NULL)) AS CURRENT_ENTERPRISES,
         COUNT_IF(VIA_PORTCO AND EVENT_DATE BETWEEN '2026-04-01' AND '2026-10-17')
           / NULLIF(COUNT_IF(EVENT_DATE BETWEEN '2026-04-01' AND '2026-10-17'), 0) AS SHARE_FROM_PORTCO_INTROS
  FROM SYNTH_SIGNAL_DB.DERIVED.THEME_MENTIONS
  GROUP BY THEME
),
r AS (
  -- current window = 200 days = 200 / (365.25 / 12) months
  SELECT w.*, (CURRENT_MENTIONS / (200 / (365.25 / 12))) / NULLIF(PRIOR_MENTIONS / 12, 0) AS MONTHLY_RATE_RATIO
  FROM w
),
ex AS (
  SELECT THEME, LISTAGG(ACCOUNT_NAME, ', ') WITHIN GROUP (ORDER BY N DESC, ACCOUNT_NAME) AS EXAMPLE_ENTERPRISES
  FROM (
    SELECT THEME, ACCOUNT_NAME, COUNT(*) AS N
    FROM SYNTH_SIGNAL_DB.DERIVED.THEME_MENTIONS
    WHERE EVENT_DATE BETWEEN '2026-04-01' AND '2026-10-17'
    GROUP BY 1, 2
    QUALIFY ROW_NUMBER() OVER (PARTITION BY THEME ORDER BY N DESC, ACCOUNT_NAME) <= 3
  )
  GROUP BY THEME
)
SELECT
  r.THEME,
  r.PRIOR_MENTIONS, r.CURRENT_MENTIONS,
  ROUND(r.MONTHLY_RATE_RATIO, 4) AS MONTHLY_RATE_RATIO,
  r.CURRENT_ENTERPRISES,
  ROUND(r.SHARE_FROM_PORTCO_INTROS, 4) AS SHARE_FROM_PORTCO_INTROS,
  ex.EXAMPLE_ENTERPRISES,
  ROUND(b.MONTHLY_RATE_RATIO, 4) AS BASELINE_RATIO
FROM r
JOIN ex USING (THEME)
CROSS JOIN (SELECT MONTHLY_RATE_RATIO FROM r WHERE THEME = 'AI agents (baseline)') b;

CREATE OR REPLACE VIEW SYNTH_SIGNAL_DB.DERIVED.ENTERPRISE_QUARTERLY
  COMMENT = 'Same shape as SIGNAL_SAVED_FILES.ENTERPRISE_QUARTERLY, computed from CRM'
AS
WITH tot AS (
  SELECT YEAR(PERFORMED_DATE) || '-Q' || QUARTER(PERFORMED_DATE) AS QUARTER, COUNT(*) AS TOTAL_ACTIVITIES
  FROM SYNTH_SIGNAL_DB.ANALYTICS.FACT_CRM_EVENTS
  WHERE TO_DATE(PERFORMED_DATE) >= '2024-07-01'
  GROUP BY 1
),
grid AS (
  SELECT d.THEME, t.QUARTER, t.TOTAL_ACTIVITIES
  FROM SYNTH_SIGNAL_DB.ANALYTICS.DIM_THEME_DEFINITIONS d CROSS JOIN tot t
  WHERE d.THEME <> 'AI agents (baseline)'
),
m AS (
  SELECT THEME, YEAR(EVENT_DATE) || '-Q' || QUARTER(EVENT_DATE) AS QUARTER, COUNT(*) AS MENTIONS
  FROM SYNTH_SIGNAL_DB.DERIVED.THEME_MENTIONS GROUP BY 1, 2
)
SELECT g.THEME, g.QUARTER, COALESCE(m.MENTIONS, 0) AS MENTIONS, g.TOTAL_ACTIVITIES
FROM grid g LEFT JOIN m USING (THEME, QUARTER);

-- Enterprise FDE activity from CRM; expert document counts stay from the saved file
-- because expert calls have no underlying records in this database.
CREATE OR REPLACE VIEW SYNTH_SIGNAL_DB.DERIVED.FDE_OTHER_QUARTERLY
  COMMENT = 'Enterprise FDE activities from CRM; expert docs from SIGNAL_SAVED_FILES'
AS
SELECT q.QUARTER,
       q.MENTIONS AS ENTERPRISE_FDE_ACTIVITIES,
       COALESCE(s.EXPERT_FDE_DOCS, 0) AS EXPERT_FDE_DOCS
FROM SYNTH_SIGNAL_DB.DERIVED.ENTERPRISE_QUARTERLY q
LEFT JOIN SYNTH_SIGNAL_DB.SIGNAL_SAVED_FILES.FDE_OTHER_QUARTERLY s USING (QUARTER)
WHERE q.THEME = 'Forward deployed engineering';
