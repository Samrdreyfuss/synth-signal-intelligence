-- ============================================================================
-- 13_emerging_schedule.sql
-- Automation: a stream on FACT_CRM_EVENTS triggers an hourly pipeline that embeds new
-- texts, re-clusters, names new/grown clusters and snapshots signals into history.
-- The task is created SUSPENDED; resume it with:
--   ALTER TASK SYNTH_SIGNAL_DB.EMERGING.REFRESH_EMERGING RESUME;
-- Run once by hand with:  CALL SYNTH_SIGNAL_DB.EMERGING.REFRESH_EMERGING_TOPICS();
-- ============================================================================
CREATE TABLE IF NOT EXISTS SYNTH_SIGNAL_DB.EMERGING.CLUSTER_SIGNAL_HISTORY (
  SNAPSHOT_AT TIMESTAMP_LTZ, CLUSTER_ID VARCHAR, TOPIC_NAME VARCHAR, STATUS VARCHAR,
  RECORDS INT, RECENT_RECORDS INT, VELOCITY FLOAT, ACCOUNTS INT, SOURCES INT, EMERGENCE_SCORE FLOAT
) COMMENT = 'Snapshot of CLUSTER_SIGNALS after each refresh';

CREATE TABLE IF NOT EXISTS SYNTH_SIGNAL_DB.EMERGING.REFRESH_LOG (
  REFRESHED_AT TIMESTAMP_LTZ, NEW_CRM_ROWS INT
) COMMENT = 'One row per pipeline run; reading the stream here advances its offset';

CREATE STREAM IF NOT EXISTS SYNTH_SIGNAL_DB.EMERGING.CRM_EVENTS_STREAM
  ON TABLE SYNTH_SIGNAL_DB.ANALYTICS.FACT_CRM_EVENTS APPEND_ONLY = TRUE;

CREATE OR REPLACE PROCEDURE SYNTH_SIGNAL_DB.EMERGING.REFRESH_EMERGING_TOPICS()
RETURNS VARCHAR
LANGUAGE SQL
AS
$$
DECLARE
  embed_msg VARCHAR;
  cluster_msg VARCHAR;
  name_msg VARCHAR;
BEGIN
  -- consume the stream (offset advances only on DML) so the task's WHEN condition resets
  INSERT INTO SYNTH_SIGNAL_DB.EMERGING.REFRESH_LOG (REFRESHED_AT, NEW_CRM_ROWS)
    SELECT CURRENT_TIMESTAMP(), COUNT(*) FROM SYNTH_SIGNAL_DB.EMERGING.CRM_EVENTS_STREAM;
  CALL SYNTH_SIGNAL_DB.EMERGING.EMBED_NEW_TEXTS() INTO :embed_msg;
  CALL SYNTH_SIGNAL_DB.EMERGING.CLUSTER_RECORDS() INTO :cluster_msg;
  CALL SYNTH_SIGNAL_DB.EMERGING.NAME_CLUSTERS() INTO :name_msg;
  -- second pass retries any cluster whose structured-output call returned nothing
  CALL SYNTH_SIGNAL_DB.EMERGING.NAME_CLUSTERS();
  INSERT INTO SYNTH_SIGNAL_DB.EMERGING.CLUSTER_SIGNAL_HISTORY
  SELECT CURRENT_TIMESTAMP(), CLUSTER_ID, TOPIC_NAME, STATUS, RECORDS, RECENT_RECORDS, VELOCITY,
         ACCOUNTS, SOURCES, EMERGENCE_SCORE
  FROM SYNTH_SIGNAL_DB.EMERGING.CLUSTER_SIGNALS;
  RETURN embed_msg || '; ' || cluster_msg || '; ' || name_msg;
END;
$$;

CREATE OR REPLACE TASK SYNTH_SIGNAL_DB.EMERGING.REFRESH_EMERGING
  WAREHOUSE = DEFAULT_WH
  SCHEDULE = '60 MINUTE'
  COMMENT = 'Embed new records, re-cluster, name clusters, snapshot signals'
  WHEN SYSTEM$STREAM_HAS_DATA('SYNTH_SIGNAL_DB.EMERGING.CRM_EVENTS_STREAM')
AS
  CALL SYNTH_SIGNAL_DB.EMERGING.REFRESH_EMERGING_TOPICS();
