-- ============================================================================
-- 11_emerging_signals.sql
-- Per discovered cluster: velocity, spread, noise checks, nearest theme and status.
-- Also drift for known themes (recent additions vs long-run centre).
-- As-of date = latest record date (2026-10-17 in the synthetic data).
-- ============================================================================
CREATE OR REPLACE VIEW SYNTH_SIGNAL_DB.EMERGING.CLUSTER_MEMBERS
  COMMENT = 'Records assigned to discovered clusters, with source, company and embedding'
AS
SELECT rc.CLUSTER_ID, r.RECORD_ID, r.SOURCE, r.ACCOUNT_ID, r.ENTITY_NAME, r.RECORDED_BY_ID,
       r.RECORD_DATE, r.TEXT, p.INDUSTRY, e.EMBEDDING
FROM SYNTH_SIGNAL_DB.EMERGING.RECORD_CLUSTERS rc
JOIN SYNTH_SIGNAL_DB.EMERGING.SOURCE_RECORDS r USING (RECORD_ID)
JOIN SYNTH_SIGNAL_DB.EMERGING.TEXT_EMBEDDINGS e USING (TEXT_HASH)
LEFT JOIN SYNTH_SIGNAL_DB.ANALYTICS.DIM_COMPANY_PROFILES p ON p.ACCOUNT_ID = r.ACCOUNT_ID
WHERE rc.CLUSTER_ID LIKE 'C%';

CREATE OR REPLACE VIEW SYNTH_SIGNAL_DB.EMERGING.CLUSTER_SIGNALS
  COMMENT = 'Emergence signals and status for each discovered cluster'
AS
WITH cfg AS (
  SELECT MAX(IFF(KEY = 'RECENT_DAYS', VALUE, NULL)) AS RECENT_DAYS,
         MAX(IFF(KEY = 'NEW_TOPIC_MAX_AGE_DAYS', VALUE, NULL)) AS MAX_AGE,
         MAX(IFF(KEY = 'MIN_ACCOUNTS', VALUE, NULL)) AS MIN_ACCOUNTS,
         MAX(IFF(KEY = 'MAX_TOP_ACCOUNT_SHARE', VALUE, NULL)) AS MAX_TOP_SHARE
  FROM SYNTH_SIGNAL_DB.EMERGING.CONFIG
),
as_of_date AS (SELECT MAX(RECORD_DATE) AS AS_OF FROM SYNTH_SIGNAL_DB.EMERGING.SOURCE_RECORDS),
m AS (
  SELECT cm.*, a.AS_OF, c.RECENT_DAYS,
         cm.RECORD_DATE > DATEADD(day, -c.RECENT_DAYS, a.AS_OF) AS IS_RECENT,
         cm.RECORD_DATE <= DATEADD(day, -c.RECENT_DAYS, a.AS_OF)
           AND cm.RECORD_DATE > DATEADD(day, -2 * c.RECENT_DAYS, a.AS_OF) AS IS_PRIOR
  FROM SYNTH_SIGNAL_DB.EMERGING.CLUSTER_MEMBERS cm CROSS JOIN as_of_date a CROSS JOIN cfg c
),
top_acct AS (
  SELECT CLUSTER_ID, MAX(N) / SUM(N) AS TOP_ACCOUNT_SHARE
  FROM (SELECT CLUSTER_ID, ACCOUNT_ID, COUNT(*) AS N FROM m GROUP BY 1, 2) GROUP BY 1
),
agg AS (
  SELECT CLUSTER_ID,
         COUNT(*) AS RECORDS,
         MIN(RECORD_DATE) AS FIRST_SEEN, MAX(RECORD_DATE) AS LAST_SEEN,
         -- date by which 10% of members had arrived: robust to a few stray early records
         DATEADD(day, PERCENTILE_DISC(0.1) WITHIN GROUP (ORDER BY DATEDIFF(day, '2000-01-01'::DATE, RECORD_DATE)),
                 '2000-01-01'::DATE) AS EMERGED_ON,
         COUNT_IF(IS_RECENT) AS RECENT_RECORDS, COUNT_IF(IS_PRIOR) AS PRIOR_RECORDS,
         COUNT(DISTINCT ACCOUNT_ID) AS ACCOUNTS,
         COUNT(DISTINCT IFF(IS_RECENT, ACCOUNT_ID, NULL)) AS RECENT_ACCOUNTS,
         COUNT(DISTINCT RECORDED_BY_ID) AS REPS,
         COUNT(DISTINCT SOURCE) AS SOURCES,
         ARRAY_TO_STRING(ARRAY_AGG(DISTINCT SOURCE) WITHIN GROUP (ORDER BY SOURCE), ', ') AS SOURCE_LIST,
         COUNT(DISTINCT INDUSTRY) AS INDUSTRIES,
         ANY_VALUE(AS_OF) AS AS_OF
  FROM m GROUP BY 1
),
weekly AS (
  SELECT CLUSTER_ID, DATE_TRUNC('week', RECORD_DATE) AS WK, COUNT(*) AS N FROM m GROUP BY 1, 2
),
burst AS (
  -- z-score of the latest 4 weeks' mean vs earlier weeks (zero-filled not needed for new clusters)
  SELECT w.CLUSTER_ID,
         AVG(IFF(w.WK > DATEADD(week, -4, a.AS_OF), w.N, NULL)) AS RECENT_WEEKLY,
         AVG(IFF(w.WK <= DATEADD(week, -4, a.AS_OF), w.N, NULL)) AS EARLIER_WEEKLY
  FROM weekly w CROSS JOIN as_of_date a GROUP BY 1
),
nearest AS (
  SELECT c.CLUSTER_ID, t.THEME AS NEAREST_THEME,
         VECTOR_COSINE_SIMILARITY(c.CENTROID, t.EMBEDDING) AS THEME_SIMILARITY
  FROM SYNTH_SIGNAL_DB.EMERGING.CLUSTERS c
  CROSS JOIN SYNTH_SIGNAL_DB.ANALYTICS.THEME_EMBEDDINGS t
  QUALIFY ROW_NUMBER() OVER (PARTITION BY c.CLUSTER_ID ORDER BY THEME_SIMILARITY DESC) = 1
)
SELECT
  a.CLUSTER_ID,
  pr.TOPIC_NAME, pr.DEFINITION, pr.RELATION, pr.RELATED_THEME, pr.KEY_TERMS, pr.REASON,
  cl.CREATED_WEEK, a.FIRST_SEEN, a.EMERGED_ON, a.LAST_SEEN,
  DATEDIFF(day, a.EMERGED_ON, a.AS_OF) AS AGE_DAYS,
  a.RECORDS, a.RECENT_RECORDS, a.PRIOR_RECORDS,
  ROUND((a.RECENT_RECORDS + 1) / (a.PRIOR_RECORDS + 1), 2) AS VELOCITY,
  ROUND(b.RECENT_WEEKLY, 2) AS RECENT_WEEKLY, ROUND(b.EARLIER_WEEKLY, 2) AS EARLIER_WEEKLY,
  a.ACCOUNTS, a.RECENT_ACCOUNTS, a.REPS, a.SOURCES, a.SOURCE_LIST, a.INDUSTRIES,
  ROUND(t.TOP_ACCOUNT_SHARE, 3) AS TOP_ACCOUNT_SHARE,
  n.NEAREST_THEME, ROUND(n.THEME_SIMILARITY, 3) AS THEME_SIMILARITY,
  ROUND(1 - n.THEME_SIMILARITY, 3) AS UNIQUENESS,
  ROUND((1 - n.THEME_SIMILARITY)
        * LN(1 + (a.RECENT_RECORDS + 1) / (a.PRIOR_RECORDS + 1))
        * LN(1 + a.RECENT_ACCOUNTS)
        * (1 + 0.25 * (a.SOURCES - 1)), 3) AS EMERGENCE_SCORE,
  CASE
    WHEN s.STATUS IS NOT NULL THEN s.STATUS
    WHEN a.ACCOUNTS < cfg.MIN_ACCOUNTS OR t.TOP_ACCOUNT_SHARE > cfg.MAX_TOP_SHARE THEN 'Noise'
    WHEN pr.RELATION = 'sub-topic' THEN 'Emerging sub-topic'
    WHEN pr.RELATION = 'variant' THEN 'Variant'
    WHEN DATEDIFF(day, a.EMERGED_ON, a.AS_OF) <= cfg.MAX_AGE
         AND a.RECENT_RECORDS >= a.PRIOR_RECORDS AND a.RECENT_ACCOUNTS >= cfg.MIN_ACCOUNTS THEN 'New topic'
    ELSE 'Watch'
  END AS STATUS,
  s.STATUS IS NOT NULL AS REVIEWED
FROM agg a
JOIN SYNTH_SIGNAL_DB.EMERGING.CLUSTERS cl USING (CLUSTER_ID)
JOIN burst b USING (CLUSTER_ID)
JOIN top_acct t USING (CLUSTER_ID)
JOIN nearest n USING (CLUSTER_ID)
CROSS JOIN cfg
LEFT JOIN SYNTH_SIGNAL_DB.EMERGING.CLUSTER_PROFILES pr USING (CLUSTER_ID)
LEFT JOIN SYNTH_SIGNAL_DB.EMERGING.CLUSTER_REVIEW s USING (CLUSTER_ID);
