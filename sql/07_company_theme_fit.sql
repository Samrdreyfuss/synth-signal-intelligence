-- ============================================================================
-- 07_company_theme_fit.sql
-- Cortex AI matching of companies to themes, plus the company x theme relevance view.
-- Uses AI_EMBED once (~130k input tokens) and stores vectors, so the dashboard
-- never calls Cortex. Re-run only when descriptions or definitions change.
-- ============================================================================
CREATE OR REPLACE TABLE SYNTH_SIGNAL_DB.ANALYTICS.THEME_EMBEDDINGS
  COMMENT = 'AI_EMBED(snowflake-arctic-embed-l-v2.0) of DIM_THEME_DEFINITIONS.DEFINITION'
AS
SELECT THEME, DEFINITION,
       AI_EMBED('snowflake-arctic-embed-l-v2.0', DEFINITION) AS EMBEDDING
FROM SYNTH_SIGNAL_DB.ANALYTICS.DIM_THEME_DEFINITIONS;

CREATE OR REPLACE TABLE SYNTH_SIGNAL_DB.ANALYTICS.COMPANY_EMBEDDINGS
  COMMENT = 'AI_EMBED(snowflake-arctic-embed-l-v2.0) of DIM_COMPANY_PROFILES.DESCRIPTION'
AS
SELECT ACCOUNT_ID, AI_EMBED('snowflake-arctic-embed-l-v2.0', DESCRIPTION) AS EMBEDDING
FROM SYNTH_SIGNAL_DB.ANALYTICS.DIM_COMPANY_PROFILES;

-- Raw cosine similarity for every company x theme, plus a 0-1 PROFILE_FIT that is
-- min-max scaled within each company (so "best fit for this company" = 1).
CREATE OR REPLACE TABLE SYNTH_SIGNAL_DB.ANALYTICS.COMPANY_THEME_FIT
  COMMENT = 'Cortex embedding similarity between company descriptions and theme definitions'
AS
WITH s AS (
  SELECT c.ACCOUNT_ID, t.THEME,
         VECTOR_COSINE_SIMILARITY(c.EMBEDDING, t.EMBEDDING) AS SIMILARITY
  FROM SYNTH_SIGNAL_DB.ANALYTICS.COMPANY_EMBEDDINGS c
  CROSS JOIN SYNTH_SIGNAL_DB.ANALYTICS.THEME_EMBEDDINGS t
)
SELECT ACCOUNT_ID, THEME, SIMILARITY,
       (SIMILARITY - MIN(SIMILARITY) OVER (PARTITION BY ACCOUNT_ID))
         / NULLIF(MAX(SIMILARITY) OVER (PARTITION BY ACCOUNT_ID) - MIN(SIMILARITY) OVER (PARTITION BY ACCOUNT_ID), 0)
         AS PROFILE_FIT,
       RANK() OVER (PARTITION BY ACCOUNT_ID ORDER BY SIMILARITY DESC) AS FIT_RANK
FROM s;

-- Company x theme relevance: Cortex fit vs what the company actually talks about.
CREATE OR REPLACE VIEW SYNTH_SIGNAL_DB.EVIDENCE.COMPANY_THEME_RELEVANCE
  COMMENT = 'Profile fit (Cortex) vs CRM mentions and other evidence, with relationship label'
AS
WITH crm AS (
  SELECT ACCOUNT_ID, THEME, COUNT(*) AS CRM_MENTIONS, MAX(EVENT_DATE) AS LAST_MENTION,
         COUNT_IF(EVENT_DATE >= '2026-04-01') AS CURRENT_MENTIONS
  FROM SYNTH_SIGNAL_DB.DERIVED.THEME_MENTIONS GROUP BY 1, 2
),
other AS (
  SELECT ACCOUNT_ID, THEME, COUNT(*) AS OTHER_SOURCE_HITS
  FROM SYNTH_SIGNAL_DB.EVIDENCE.EVIDENCE_ITEMS
  WHERE SOURCE NOT IN ('CRM note', 'Portco intro') AND ACCOUNT_ID IS NOT NULL
  GROUP BY 1, 2
)
SELECT
  f.ACCOUNT_ID,
  p.ACCOUNT_NAME,
  p.INDUSTRY,
  f.THEME,
  ROUND(f.SIMILARITY, 4) AS SIMILARITY,
  ROUND(f.PROFILE_FIT, 4) AS PROFILE_FIT,
  f.FIT_RANK,
  ARRAY_CONTAINS(f.THEME::VARIANT, p.STATED_PRIORITIES) AS STATED_PRIORITY,
  COALESCE(c.CRM_MENTIONS, 0) AS CRM_MENTIONS,
  COALESCE(c.CURRENT_MENTIONS, 0) AS CURRENT_MENTIONS,
  c.LAST_MENTION,
  COALESCE(o.OTHER_SOURCE_HITS, 0) AS OTHER_SOURCE_HITS,
  CASE
    WHEN f.FIT_RANK <= 4 AND COALESCE(c.CRM_MENTIONS, 0) > 0 THEN 'Confirmed'
    WHEN f.FIT_RANK <= 4 THEN 'Latent fit'
    WHEN COALESCE(c.CRM_MENTIONS, 0) > 0 THEN 'Talking, off-profile'
    ELSE 'Unrelated'
  END AS RELATIONSHIP
FROM SYNTH_SIGNAL_DB.ANALYTICS.COMPANY_THEME_FIT f
JOIN SYNTH_SIGNAL_DB.ANALYTICS.DIM_COMPANY_PROFILES p USING (ACCOUNT_ID)
LEFT JOIN crm c ON c.ACCOUNT_ID = f.ACCOUNT_ID AND c.THEME = f.THEME
LEFT JOIN other o ON o.ACCOUNT_ID = f.ACCOUNT_ID AND o.THEME = f.THEME;
