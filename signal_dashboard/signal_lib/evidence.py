"""Evidence and attribution queries over SYNTH_SIGNAL_DB.EVIDENCE, plus pure helpers.

Query functions take ``run(sql, params)`` like ``signal_lib.data``. Every user-chosen
value (theme, sources, company, search text) is a qmark bind parameter.
"""

from __future__ import annotations

from typing import Optional, Sequence

import pandas as pd

from .data import AS_OF, Runner, _upper

EVIDENCE = "SYNTH_SIGNAL_DB.EVIDENCE"
ANALYTICS = "SYNTH_SIGNAL_DB.ANALYTICS"

SOURCES = ["CRM note", "Portco intro", "Portco network", "Expert call", "External scan"]
SOURCE_FAMILY = {
    "CRM note": "CRM",
    "Portco intro": "CRM",
    "Portco network": "Portco network",
    "Expert call": "Expert call",
    "External scan": "External scan",
}


# ------------------------------------------------------------------ queries

def attribution(run: Runner) -> pd.DataFrame:
    return _upper(run(f"SELECT * FROM {EVIDENCE}.THEME_ATTRIBUTION", None))


def corroboration(run: Runner) -> pd.DataFrame:
    df = _upper(run(
        f"SELECT THEME, SOURCE_FAMILIES, ARRAY_TO_STRING(FAMILIES, ', ') AS FAMILIES, "
        f"MULTI_SOURCE_ENTITIES, CONFIDENCE FROM {EVIDENCE}.THEME_CORROBORATION", None))
    return df


def _where(theme: Optional[str], sources: Optional[Sequence[str]], entity: Optional[str],
           search: Optional[str]):
    clauses, params = [], []
    if theme:
        clauses.append("THEME = ?")
        params.append(theme)
    if sources:
        # Only known labels are allowed; placeholders are generated by count, values are bound.
        allowed = [s for s in sources if s in SOURCES]
        if allowed:
            clauses.append(f"SOURCE IN ({', '.join('?' for _ in allowed)})")
            params.extend(allowed)
    if entity:
        clauses.append("ENTITY_NAME = ?")
        params.append(entity)
    if search:
        clauses.append("(SNIPPET ILIKE ? ESCAPE '!' OR ENTITY_NAME ILIKE ? ESCAPE '!')")
        term = search.strip().replace("!", "!!").replace("%", "!%").replace("_", "!_")
        like = f"%{term}%"
        params.extend([like, like])
    return ("WHERE " + " AND ".join(clauses)) if clauses else "", params


def evidence(run: Runner, theme: Optional[str] = None, sources: Optional[Sequence[str]] = None,
             entity: Optional[str] = None, search: Optional[str] = None,
             limit: int = 200) -> pd.DataFrame:
    """Evidence items, newest first (undated aggregate rows last)."""
    where, params = _where(theme, sources, entity, search)
    sql = f"""
        SELECT EVIDENCE_ID, THEME, SOURCE, ENTITY_NAME, ENTITY_TYPE, ACCOUNT_ID, EVIDENCE_DATE,
               SNIPPET, LINK, RECORDED_BY, WEIGHT, SOURCE_TABLE, SOURCE_KEY
        FROM {EVIDENCE}.EVIDENCE_ITEMS
        {where}
        ORDER BY EVIDENCE_DATE DESC NULLS LAST, EVIDENCE_ID
        LIMIT {max(1, min(int(limit), 2000))}
    """
    return _upper(run(sql, params or None))


def evidence_count(run: Runner, theme: Optional[str] = None,
                   sources: Optional[Sequence[str]] = None, entity: Optional[str] = None,
                   search: Optional[str] = None) -> int:
    where, params = _where(theme, sources, entity, search)
    df = _upper(run(f"SELECT COUNT(*) AS N FROM {EVIDENCE}.EVIDENCE_ITEMS {where}", params or None))
    return int(df["N"].iloc[0]) if len(df) else 0


def entity_sources(run: Runner, theme: str) -> pd.DataFrame:
    """Per company in a theme: evidence count by source (long form)."""
    sql = f"""
        SELECT ENTITY_NAME, ENTITY_TYPE, ANY_VALUE(ACCOUNT_ID) AS ACCOUNT_ID, SOURCE,
               COUNT(*) AS ITEMS, MAX(EVIDENCE_DATE) AS LAST_SEEN
        FROM {EVIDENCE}.EVIDENCE_ITEMS
        WHERE THEME = ?
        GROUP BY ENTITY_NAME, ENTITY_TYPE, SOURCE
    """
    return _upper(run(sql, [theme]))


def timeline(run: Runner, theme: str) -> pd.DataFrame:
    """Monthly dated evidence by source for a theme."""
    sql = f"""
        SELECT DATE_TRUNC('month', EVIDENCE_DATE) AS MONTH, SOURCE, COUNT(*) AS ITEMS
        FROM {EVIDENCE}.EVIDENCE_ITEMS
        WHERE THEME = ? AND EVIDENCE_DATE IS NOT NULL
        GROUP BY 1, 2
        ORDER BY 1
    """
    return _upper(run(sql, [theme]))


def entity_profile(run: Runner, entity: str) -> dict:
    """Everything known about one company: CRM account facts plus evidence by theme and source."""
    account = _upper(run(
        f"""
        SELECT c.ACCOUNT_NAME, c.WEBSITE_CLEANED AS WEBSITE,
               IFF(c.ACCOUNT_TYPE ILIKE 'portfolio%', 'Portfolio', 'Prospect') AS SEGMENT,
               NULLIF(c.OWNER_NAME, '') AS OWNER_NAME,
               (c.OWNER_NAME IS NULL OR c.OWNER_NAME = '' OR c.OWNER_NAME ILIKE 'unassigned%') AS UNOWNED,
               c.DATE_OF_LAST_ACTIVITY,
               (c.DATE_OF_LAST_ACTIVITY IS NULL
                OR c.DATE_OF_LAST_ACTIVITY < DATEADD(day, -90, ?::DATE)) AS STALE,
               c.LAST_LOSS_DROP_REASON
        FROM {ANALYTICS}.DIM_SALESFORCE__COMPANIES c
        WHERE LOWER(c.ACCOUNT_NAME) = LOWER(?)
        LIMIT 1
        """, [AS_OF.isoformat(), entity]))
    mix = _upper(run(
        f"""
        SELECT THEME, SOURCE, COUNT(*) AS ITEMS
        FROM {EVIDENCE}.EVIDENCE_ITEMS WHERE ENTITY_NAME = ?
        GROUP BY 1, 2
        """, [entity]))
    return {"account": account, "mix": mix}


# ------------------------------------------------------------------ pure helpers

def attribution_shares(attr: pd.DataFrame) -> pd.DataFrame:
    """Recompute SHARE_OF_THEME from EVIDENCE_ITEMS so it always sums to 1 per theme."""
    out = attr.copy()
    out["SHARE_OF_THEME"] = out["EVIDENCE_ITEMS"] / out.groupby("THEME")["EVIDENCE_ITEMS"].transform("sum")
    out["SOURCE"] = pd.Categorical(out["SOURCE"], categories=SOURCES, ordered=True)
    return out.sort_values(["THEME", "SOURCE"]).reset_index(drop=True)


def source_matrix(entity_long: pd.DataFrame) -> pd.DataFrame:
    """Wide company x source table with SOURCE_FAMILIES (independent sources) and TOTAL."""
    if entity_long.empty:
        return pd.DataFrame(columns=["ENTITY_NAME", "ENTITY_TYPE", *SOURCES, "TOTAL",
                                     "SOURCE_FAMILIES", "LAST_SEEN"])
    wide = entity_long.pivot_table(index=["ENTITY_NAME", "ENTITY_TYPE"], columns="SOURCE",
                                   values="ITEMS", aggfunc="sum", fill_value=0)
    for s in SOURCES:
        if s not in wide.columns:
            wide[s] = 0
    wide = wide[SOURCES]
    families = pd.DataFrame({fam: wide[[s for s, f in SOURCE_FAMILY.items() if f == fam]].sum(axis=1) > 0
                             for fam in dict.fromkeys(SOURCE_FAMILY.values())})
    wide["TOTAL"] = wide[SOURCES].sum(axis=1)
    wide["SOURCE_FAMILIES"] = families.sum(axis=1)
    last = (entity_long.assign(LAST_SEEN=pd.to_datetime(entity_long["LAST_SEEN"], errors="coerce"))
            .groupby(["ENTITY_NAME", "ENTITY_TYPE"])["LAST_SEEN"].max())
    wide["LAST_SEEN"] = last
    return (wide.reset_index()
            .sort_values(["SOURCE_FAMILIES", "TOTAL"], ascending=False)
            .reset_index(drop=True))


def intro_share_check(attr: pd.DataFrame, themes: pd.DataFrame) -> pd.DataFrame:
    """Share of CRM evidence via portco intros vs the saved share_from_portco_intros."""
    crm = attr[attr["SOURCE"].isin(["CRM note", "Portco intro"])].assign(
        SOURCE=lambda d: d["SOURCE"].astype(str))
    piv = crm.pivot_table(index="THEME", columns="SOURCE", values="EVIDENCE_ITEMS",
                          aggfunc="sum", fill_value=0)
    for s in ["CRM note", "Portco intro"]:
        if s not in piv.columns:
            piv[s] = 0
    piv["CRM_INTRO_SHARE"] = piv["Portco intro"] / (piv["Portco intro"] + piv["CRM note"]).where(
        lambda x: x > 0)
    out = piv[["CRM_INTRO_SHARE"]].reset_index().merge(
        themes[["THEME", "SHARE_FROM_PORTCO_INTROS"]], on="THEME", how="left")
    for col in ["CRM_INTRO_SHARE", "SHARE_FROM_PORTCO_INTROS"]:
        out[col] = pd.to_numeric(out[col], errors="coerce").astype(float)
    out["GAP_PTS"] = (out["CRM_INTRO_SHARE"] - out["SHARE_FROM_PORTCO_INTROS"]) * 100
    return out
